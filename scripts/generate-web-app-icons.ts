/**
 * Writer: embeds the home-screen PNGs into src/web-app-icons.generated.ts.
 *
 * The Worker ships as one Bun.build module with no static-asset binding, and
 * Bun has no bytes import, so the PNGs under public/ travel as base64. The
 * icon list is the manifest's icons plus the apple-touch-icon. Run after
 * changing any of them: `bun run scripts/generate-web-app-icons.ts`.
 * src/web-app.test.ts fails while the generated module is out of date.
 */

export const APPLE_TOUCH_ICON_PATH = "/apple-touch-icon.png";

const publicDir = new URL("../public/", import.meta.url);
const outFile = new URL("../src/web-app-icons.generated.ts", import.meta.url);

export async function webAppIconPaths(): Promise<string[]> {
  const manifest = (await Bun.file(
    new URL("manifest.webmanifest", publicDir),
  ).json()) as { icons?: Array<{ src?: unknown }> };
  const paths = new Set<string>([APPLE_TOUCH_ICON_PATH]);
  for (const icon of manifest.icons ?? []) {
    if (typeof icon.src !== "string") throw new Error("icon without src");
    paths.add(icon.src);
  }
  for (const path of paths) {
    if (!/^\/[a-z0-9/_-]+\.png$/u.test(path) || path.includes("..")) {
      throw new Error(`web app icon must be a root-relative PNG: ${path}`);
    }
  }
  return [...paths].sort();
}

export function publicFile(path: string): URL {
  return new URL(path.slice(1), publicDir);
}

if (import.meta.main) {
  const lines = [
    "// Generated by scripts/generate-web-app-icons.ts from public/. Do not edit.",
    "",
    "/** Base64 PNG bytes keyed by the path the Worker serves them at. */",
    "export const WEB_APP_ICONS: Readonly<Record<string, string>> = {",
  ];
  for (const path of await webAppIconPaths()) {
    const bytes = new Uint8Array(
      await Bun.file(publicFile(path)).arrayBuffer(),
    );
    lines.push(
      `  ${JSON.stringify(path)}:`,
      `    ${JSON.stringify(Buffer.from(bytes).toString("base64"))},`,
    );
  }
  lines.push("};", "");
  await Bun.write(outFile, lines.join("\n"));
  console.log(`wrote ${outFile.pathname}`);
}
